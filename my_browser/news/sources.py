INTERVALS = {"lab": 30, "papers": 120, "media": 15, "analyst": 60, "community": 30}  # minutes between polls
OPPS_INTERVALS = {"aggregator": 60, "company": 180, "university": 180, "program": 360, "conference": 360, "community": 60}
PAGE_INTERVAL = 1440  # a watched page: once a day
# Days without a new post after which a source of the opportunities lane counts as silent (/sources shows it): an
# aggregator posts every few days, a program's page may rightly stay the same for a season.
SILENT_DAYS = {"aggregator": 14, "page": 90}
SILENT_DAYS_OTHER = 45


@dataclass
class Source:
    name: str
    url: str
    category: str
    owner: str
    lang: str = "en"
    primary: bool = False
    ai_filter: bool = False  # a general feed: only posts about AI are kept
    kind: str = "rss"
    interval: int = 0  # 0: the category's interval
    lane: str = "news"  # or "opps": opportunities


def _lab(name, url, owner, **kw) -> Source:
    return Source(name, url, "lab", owner, primary=True, **kw)


def _tg(channel, title, category, **kw) -> Source:
    """A public channel read through t.me/s (collectors/telegram.py); each channel is its own owner."""
    return Source(f"Telegram: {title}", channel, category, f"tg:{channel}", lang="ru", kind="telegram", **kw)


def _opp(name, url, category, owner, kind="rss", **kw) -> Source:
    """A source of the opportunities lane; a page is read once a day, the rest by category (OPPS_INTERVALS)."""
    kw.setdefault("interval", PAGE_INTERVAL if kind == "page" else OPPS_INTERVALS[category])
    return Source(name, url, category, owner, kind=kind, lane="opps", **kw)


def _opp_tg(channel, title, category, owner="", **kw) -> Source:
    """A channel of the opportunities lane; several channels of one company share its owner."""
    return _opp(f"Telegram: {title}", channel, category, owner or f"tg:{channel}", kind="telegram", **{"lang": "ru", **kw})


